"""Generate one slash-command skill per specialist (PRD s9.1, s19).

OpenClaw exposes a user-invocable skill as a slash command, so `/qtpp <task>` is
a skill named `qtpp` whose only job is to launch a direct run against A03. That
uses the gateway's own command path: no Slack app manifest change, no reinstall,
and no second routing mechanism to keep in step with the registry.

The skills are generated rather than written so they cannot drift from the
registry. Regenerate: uv run python scripts/generate_command_skills.py
Verify:     uv run python scripts/generate_command_skills.py --check
"""

from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path

from app.agents.registry import get_registry

PROJECT_ROOT = Path(__file__).resolve().parent.parent
TARGET = PROJECT_ROOT / "openclaw" / "workspace" / "skills" / "commands"

BANNER = (
    "<!-- GENERATED by scripts/generate_command_skills.py — do not edit by hand.\n"
    "     Regenerate: uv run python scripts/generate_command_skills.py\n"
    "     Verify:     uv run python scripts/generate_command_skills.py --check -->"
)

DESCRIPTION = (
    "Send one task directly to the {agent_name} ({agent_id}) — the Nucleus "
    "specialist for {purpose}. Use when the user names this specialist with "
    "/{name}, or asks for this specialist by name."
)

TEMPLATE = """---
name: {name}
description: {description}
metadata:
  short-description: Ask the {agent_name} a single question
---

{banner}

# /{name} — {agent_name}

Send one task to **{agent_id}, the {agent_name}**, and nothing else. No planning
stage, no other specialists: the user chose who should answer.

## What this specialist covers

{purpose}

## How to launch

```bash
cd "{{{{NUCLEUS_ROOT}}}}" && uv run python scripts/enqueue_run.py \\
  --request "<the user's task, verbatim, without the slash command>" \\
  --agent {agent_id} \\
  --channel "<slack channel id>" \\
  --thread "<slack thread ts>" \\
  --user "<slack user id>" \\
  --event-id "<slack event id>"
```

Pass the task **verbatim**, minus the `/{name}` prefix itself. Do not summarise it,
expand it, or add context the user did not give — the specialist plans its own work
from the words it receives.

If the user gave no task after the command, ask what they want this specialist to
do. Do not invent one.

## What to tell the user

> Run RUN-2026-0042 started. Sent to the {agent_name}.

Report the `run_ref` the script prints. The result and any documents arrive in this
thread on their own.

## What not to do

- Do not answer the pharmaceutical question yourself. This specialist exists
  because the answer needs its judgement, not yours.
- Do not route to a different specialist because you think it fits better. Say so
  and let the user decide.
- Do not invent a run reference. Use what the script returns.
"""


def skill_name(slug: str) -> str:
    """OpenClaw sanitises command names to a-z0-9_ (max 32)."""
    return slug.lower().replace("-", "_")[:32]


def render(profile) -> str:
    purpose = (profile.purpose or profile.name).strip().rstrip(".")
    name = skill_name(profile.slug)
    # A description longer than a couple of lines is unreadable in the command
    # list, and the purpose text is written for a prompt, not a menu.
    short_purpose = purpose if len(purpose) <= 120 else purpose[:117].rsplit(" ", 1)[0] + "..."
    return TEMPLATE.format(
        name=name,
        agent_id=profile.id,
        agent_name=profile.name,
        purpose=purpose,
        banner=BANNER,
        description=DESCRIPTION.format(
            agent_name=profile.name, agent_id=profile.id, purpose=short_purpose, name=name
        ),
    )


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate per-specialist command skills.")
    parser.add_argument("--check", action="store_true", help="report drift, write nothing")
    args = parser.parse_args()

    profiles = get_registry().enabled_profiles()
    expected = {skill_name(p.slug): render(p) for p in profiles}

    drift: list[str] = []
    for name, content in expected.items():
        path = TARGET / name / "SKILL.md"
        if not path.is_file() or path.read_text() != content:
            drift.append(name)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content)

    # A specialist removed from the registry loses its command.
    if TARGET.is_dir():
        for existing in TARGET.iterdir():
            if existing.is_dir() and existing.name not in expected:
                drift.append(f"{existing.name} (stale)")
                if not args.check:
                    shutil.rmtree(existing)

    if args.check and drift:
        print("command skills are out of date:", file=sys.stderr)
        for name in drift:
            print(f"  - {name}", file=sys.stderr)
        print("run: uv run python scripts/generate_command_skills.py", file=sys.stderr)
        return 1
    print(f"{len(expected)} command skill(s) in {TARGET}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
